"""The result: a proven bracket on the fewest turns to win, per seed.

Proving the full-game optimum is out of reach (HANDOFF_search_performance.md),
so what this reports is a bracket that is sound at both ends:

    lower   max(h, flow bound) at the opening. Both are admissible: h checked
            against 42,749 playthrough states and 98 proven optima, the flow
            bound against 360 and 70 (see solver.bound, solver.flow).
    upper   the shortest plan any method finds — the bots, beam search with
            plan repair, chained sub-goals — each REPLAYED to a real win
            before it counts.

The true optimum lies in [lower, upper]; the width is the headline number.

    python -m solver.bracket [seeds] [beam width]     e.g. 10 3000

Seeds run in parallel, one process each. Writes results/solver_bracket.json
(every number, and each seed's best plan in a replayable form) and
results/solver_bracket.md (the table).
"""

from __future__ import annotations

import json
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from bots._engine import (Acquire, Claim, Crystal, Discard, PlayCrystal,
                          PlayTrade, PlayUpgrade, Rest)
from solver.bound import h
from solver.chain import chain
from solver.flow import flow_bound
from solver.greedy import Plan, upper_bound, verify
from solver.improve import beam, repair
from solver.solo import new_solo_game, turns_in

# Top level of results/, where .gitignore tracks small evidence files.
OUT = Path(__file__).resolve().parent.parent / "results"


# ---------------------------------------------------------------------------
# Plans in and out of JSON, so a saved upper bound can be checked by replay
# ---------------------------------------------------------------------------

def action_to_json(a) -> dict:
    if isinstance(a, PlayCrystal):
        return {"play": "crystal", "hand": a.hand_index}
    if isinstance(a, PlayUpgrade):
        return {"play": "upgrade", "hand": a.hand_index, "upgrades": [int(c) for c in a.upgrades]}
    if isinstance(a, PlayTrade):
        return {"play": "trade", "hand": a.hand_index, "times": a.times}
    if isinstance(a, Acquire):
        return {"acquire": a.row_index, "payment": [int(c) for c in a.payment]}
    if isinstance(a, Rest):
        return {"rest": True}
    if isinstance(a, Claim):
        return {"claim": a.row_index}
    if isinstance(a, Discard):
        return {"discard": list(a.counts)}
    raise TypeError(a)


def action_from_json(d: dict):
    if "play" in d:
        kind = d["play"]
        if kind == "crystal":
            return PlayCrystal(d["hand"])
        if kind == "upgrade":
            return PlayUpgrade(d["hand"], tuple(Crystal(c) for c in d["upgrades"]))
        return PlayTrade(d["hand"], d["times"])
    if "acquire" in d:
        return Acquire(d["acquire"], tuple(Crystal(c) for c in d["payment"]))
    if "rest" in d:
        return Rest()
    if "claim" in d:
        return Claim(d["claim"])
    return Discard(tuple(d["discard"]))


def replay_saved(seed: int, saved: list[dict]) -> int:
    """Replay a saved plan; return its turns, or raise if it is not a win."""
    actions = tuple(action_from_json(d) for d in saved)
    plan = Plan(turns_in(actions), actions, "saved")
    verify(seed, plan)
    return plan.turns


# ---------------------------------------------------------------------------
# One seed
# ---------------------------------------------------------------------------

def bracket(seed: int, width: int = 1000) -> dict:
    t0 = time.time()
    opening = new_solo_game(seed=seed)
    lower_h, lower_flow = h(opening), flow_bound(opening)

    bots = upper_bound(seed)
    beamed = repair(seed, beam(seed, width), 2_000)
    chained = chain(seed).plan
    candidates = {"bots": bots, f"beam{width}+repair": beamed, "chain": chained}
    method, best = min(candidates.items(), key=lambda kv: kv[1].turns)
    verify(seed, best)

    lower = max(lower_h, lower_flow)
    return {
        "seed": seed,
        "lower": lower, "lower_h": lower_h, "lower_flow": lower_flow,
        "upper": best.turns, "upper_method": method,
        "gap": best.turns - lower,
        "candidates": {k: p.turns for k, p in candidates.items()},
        "plan": [action_to_json(a) for a in best.actions],
        "seconds": round(time.time() - t0),
    }


def _write(rows: list[dict], width: int) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "solver_bracket.json").write_text(json.dumps(
        {"beam_width": width, "seeds": rows}, indent=1), encoding="utf-8")
    lines = [
        "# Solo Century: proven bracket on the fewest turns to six golems",
        "",
        f"Generated by `python -m solver.bracket` (beam width {width}). The true",
        "optimum lies between the two bounds. Lower is max(h, flow bound) at the",
        "opening, both admissible; upper is the shortest plan found, replayed to a",
        "real win. Plans are in solver_bracket.json and replay with",
        "`solver.bracket.replay_saved`.",
        "",
        "| seed | lower (h / flow) | upper | method | gap | bots | beam+repair | chain |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        c = r["candidates"]
        beam_key = next(k for k in c if k.startswith("beam"))
        lines.append(
            f"| {r['seed']} | **{r['lower']}** ({r['lower_h']} / {r['lower_flow']}) | "
            f"**{r['upper']}** | {r['upper_method']} | {r['gap']} | {c['bots']} | "
            f"{c[beam_key]} | {c['chain']} |")
    gaps = [r["gap"] for r in rows]
    lines += ["", f"Mean gap {sum(gaps) / len(gaps):.1f} turns "
                  f"(range {min(gaps)}-{max(gaps)})."]
    (OUT / "solver_bracket.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":  # pragma: no cover - manual run
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 10
    width = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
    t = time.time()
    with ProcessPoolExecutor(max_workers=min(n, 10)) as pool:
        rows = list(pool.map(bracket, range(n), [width] * n))
    _write(rows, width)
    for r in rows:
        print(f"seed {r['seed']}: [{r['lower']}, {r['upper']}] gap {r['gap']}  via {r['upper_method']}  ({r['seconds']}s)")
    print(f"wrote {OUT / 'solver_bracket.md'}  ({time.time() - t:.0f}s wall)")
